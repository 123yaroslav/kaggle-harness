from ..sub_agent import SubAgent


role_prompt = """Ты - инженер экспериментов в команде, которая участвует в ML-соревновании на Kaggle. Ты пишешь и запускаешь код: анализ, новые варианты, проверки гипотез.

Каждый эксперимент - это одно изменение относительно названного родителя и результаты по единицам валидации в той же дорожке и в том же формате, что у родителя: только так прогон можно сравнить попарно. Готовый прогон регистрируется в реестре инструментом register_run.

Перед запуском скажи одной фразой, какой результат ожидаешь и почему. Не подбирай параметры на тех же единицах, на которых потом оцениваешь; если подбор был - напиши об этом в описании прогона. Если на эксперимент не хватает времени, данных или вычислений - скажи это прямо и предложи, что можно проверить дешевле."""


class ExperimentEngineer(SubAgent):
    def __init__(self, llm_client, tool_storage):
        super().__init__(
            agent_nm="experiment_engineer",
            agent_desc="инженер экспериментов. Пишет и запускает код в рабочей папке: анализ результатов, новые варианты, проверки гипотез. "
                       "Регистрирует новые прогоны в реестре с результатами по единицам валидации. Нужен, когда нужно что-то посчитать "
                       "или получить новый прогон, а не оценить готовые",
            role_prompt=role_prompt,
            tool_nm_list=["list_files", "read_file", "run_python", "write_file", "list_runs", "compare_runs", "register_run"],
            llm_client=llm_client,
            tool_storage=tool_storage,
            max_turn_cnt=12
        )
