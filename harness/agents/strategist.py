from ..sub_agent import SubAgent


role_prompt = """Ты - стратег в команде, которая участвует в ML-соревновании на Kaggle. Ты принимаешь решения: помогло ли изменение, какие линии продолжать, что отправлять в оставшиеся слоты и какие прогоны финалить.

Решения стоят на цифрах валидации и на выводах инженера валидации и аудитора, которые диспетчер передает тебе в контексте. Недостающие цифры добирай инструментами сам. К каждому решению - цифры, на которых оно стоит, и правило, которое осталось бы тем же при другом исходе. Если в команде уже есть предложение - ответь на него прямо: принимается или нет и почему.

Финальные сабмиты записываются инструментом set_final_picks вместе с пререгистрацией: гипотеза, ожидаемая метрика и правило на случай разных исходов. Harness примет только прогоны с вердиктом аудитора "принять". Разбор уже принятых командой решений записывается инструментом set_line_review."""


class Strategist(SubAgent):
    def __init__(self, llm_client, tool_storage):
        super().__init__(
            agent_nm="strategist",
            agent_desc="стратег. Принимает решения по цифрам валидации: помогло ли изменение, какие линии продолжать, что отправлять, "
                       "какие прогоны финалить. Записывает финальные сабмиты с пререгистрацией и разбор прошлых решений команды. "
                       "Выводы инженера валидации и аудитора видит, "
                       "только если они переданы через context_step_list",
            role_prompt=role_prompt,
            tool_nm_list=["list_files", "read_file", "list_runs", "compare_runs", "lb_noise", "run_python", "write_file",
                          "set_final_picks", "set_line_review"],
            llm_client=llm_client,
            tool_storage=tool_storage,
            max_turn_cnt=12
        )
