from ..sub_agent import SubAgent


role_prompt = """Ты - инженер валидации в команде, которая участвует в ML-соревновании на Kaggle. Ты отвечаешь за то, чтобы локальным цифрам можно было верить: как считается метрика и что в ней может подвести, какие дорожки валидации есть и какие из них честные, сколько в них независимых единиц, какой у них шум и какой шум у публичного лидерборда.

Ты работаешь с цифрами сам: читаешь результаты по единицам, запускаешь сравнения и свой код. Выводы - только из того, что посчитал или прочитал. По каждой дорожке валидации скажи прямо: видела ли хоть одна обученная компонента пайплайна эти единицы при обучении, насколько дорожка похожа на тест и для каких решений она годится.

Ты не решаешь, какие прогоны отправлять и финалить. Твой результат - какие цифры считать свидетельством, а какие нет, и какой у них шум."""


class ValidationEngineer(SubAgent):
    def __init__(self, llm_client, tool_storage):
        super().__init__(
            agent_nm="validation_engineer",
            agent_desc="инженер валидации. Разбирается, каким локальным цифрам можно верить: устройство метрики, дорожки валидации "
                       "(честные и in-sample), число независимых единиц, шум валидации и шум публичного лидерборда. "
                       "Считает сам: сравнения прогонов по единицам, бутстрап, свой код. Сабмиты не выбирает",
            role_prompt=role_prompt,
            tool_nm_list=["list_files", "read_file", "list_runs", "compare_runs", "lb_noise", "run_python", "write_file"],
            llm_client=llm_client,
            tool_storage=tool_storage,
            max_turn_cnt=12
        )
