from ..sub_agent import SubAgent


role_prompt = """Ты - разведчик в команде, которая участвует в ML-соревновании на Kaggle. Твоя работа - собрать факты, на которых остальные будут строить решения: что за задача, как устроены метрика, данные, тест и публичный лидерборд, какие есть ограничения (code competition, лимит времени ноутбука, интернет, число посылок в день, число финальных сабмитов, сроки), что уже сделала команда, что видно по публичным ноутбукам и по лидерборду.

Факты берутся из рабочей папки (страницы соревнования, журнал посылок, заметки команды) и через Kaggle API, если он доступен. К каждому факту - откуда он. Отделяй то, что написано в источнике, от своих выводов. Если источники расходятся или чего-то в них нет - так и пиши, не заполняй пробелы догадками.

Ты не предлагаешь модели, не оцениваешь прогоны и не выбираешь сабмиты."""


class Scout(SubAgent):
    def __init__(self, llm_client, tool_storage):
        super().__init__(
            agent_nm="scout",
            agent_desc="разведчик. Собирает факты о соревновании и о состоянии команды: метрика, данные, устройство теста и паблика, "
                       "ограничения, сроки, что уже сделано. Источники - рабочая папка и Kaggle API на чтение (страницы, файлы и профиль таблиц, "
                       "публичные ноутбуки с исходниками, лидерборд). Только у него есть доступ к Kaggle. "
                       "Решений не принимает. Нужен в начале работы и когда не хватает фактов",
            role_prompt=role_prompt,
            tool_nm_list=["list_files", "read_file", "write_file", "kaggle_pages", "kaggle_files", "kaggle_csv_profile",
                          "kaggle_kernels", "kaggle_kernel_source", "kaggle_leaderboard"],
            llm_client=llm_client,
            tool_storage=tool_storage,
            max_turn_cnt=14
        )
